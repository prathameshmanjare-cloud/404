import type { Reply, Status, Tier } from "../types";

export const STATUS: Record<Status, { label: string; tone: string; help: string }> = {
  done: { label: "Done", tone: "ok", help: "Code generated, checked and tested." },
  awaiting_approval: {
    label: "Needs approval",
    tone: "warn",
    help: "The code touches files, the OS or the network. An admin must approve it before anything runs.",
  },
  escalated: { label: "Sent to a person", tone: "warn", help: "A support ticket was opened for a person to follow up." },
  denied: { label: "Blocked", tone: "bad", help: "The safety policy blocked this code. Nothing was executed." },
  rejected: { label: "Rejected", tone: "bad", help: "An admin rejected this code. Nothing was executed." },
  refused: { label: "Not supported", tone: "muted", help: "This request is outside what the assistant does." },
  unavailable: {
    label: "Unavailable",
    tone: "bad",
    help: "The models are unavailable and there is no built-in template for this task. A ticket was opened.",
  },
  invalid_output: {
    label: "Try again",
    tone: "warn",
    help: "The model's answer was not valid Python, even after asking it again. Nothing was executed.",
  },
  sql: { label: "SQL ready", tone: "ok", help: "A read-only query was written and checked. It was not executed." },
};

export function statusInfo(s: Status) {
  return STATUS[s] ?? { label: s, tone: "muted", help: "" };
}

export const TIER: Record<Tier, { label: string; help: string }> = {
  primary: { label: "Primary model", help: "Generated by the main model." },
  fallback: { label: "Fallback model", help: "The main model was unavailable, so the backup model answered." },
  template: {
    label: "Built-in template",
    help: "No model answered, so a reviewed built-in solution for this common task was used.",
  },
  none: { label: "Rules only", help: "No model was used; only the built-in rules decided." },
};

export type StepState = "done" | "active" | "warn" | "failed" | "skipped" | "pending";
export interface Step {
  label: string;
  state: StepState;
  note: string;
}

export function steps(r: Reply): Step[] {
  const decision = r.policy?.decision;
  const isSql = !!r.sql || r.status === "sql";
  if (r.status === "escalated") {
    return [
      { label: "Understand", state: "warn", note: "Handed to a person" },
      { label: "Generate", state: "skipped", note: "Not started" },
    ];
  }
  if (r.status === "refused") {
    return [{ label: "Understand", state: "failed", note: r.route === "other" ? "Not a coding task" : "Refused" }];
  }
  if (isSql) {
    return [
      { label: "Understand", state: "done", note: "SQL query" },
      { label: "Write query", state: r.sql ? "done" : "failed", note: r.sql ? "Written" : "Failed" },
      {
        label: "Read-only check",
        state: decision === "allow" ? "done" : "failed",
        note: decision === "allow" ? "Passed" : "Blocked",
      },
    ];
  }
  const out: Step[] = [{ label: "Understand", state: "done", note: "Python function" }];
  out.push(r.code ? { label: "Generate", state: "done", note: "Code and tests" } : { label: "Generate", state: "failed", note: "Not available" });
  if (!r.code) return out;
  out.push(
    decision === "deny"
      ? { label: "Safety check", state: "failed", note: "Blocked" }
      : decision === "needs_approval"
        ? { label: "Safety check", state: "warn", note: "Needs approval" }
        : { label: "Safety check", state: "done", note: "Passed" },
  );
  if (decision === "needs_approval") {
    out.push(
      r.status === "awaiting_approval"
        ? { label: "Approval", state: "active", note: "Waiting for admin" }
        : r.status === "rejected"
          ? { label: "Approval", state: "failed", note: "Rejected" }
          : { label: "Approval", state: "done", note: "Approved" },
    );
  }
  const run = r.run;
  out.push(
    !run
      ? { label: "Tests", state: decision === "deny" || r.status === "rejected" ? "skipped" : "pending", note: "Not run" }
      : run.timed_out
        ? { label: "Tests", state: "failed", note: "Timed out" }
        : run.exit_code === 0
          ? { label: "Tests", state: "done", note: "Passed" }
          : { label: "Tests", state: "failed", note: "Failed" },
  );
  const runnable = r.status === "done";
  out.push({ label: "Run it", state: runnable ? "active" : "pending", note: runnable ? "Ready" : "Locked" });
  return out;
}
